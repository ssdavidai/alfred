def test_at_least_eight_substantive_matters() -> None:
    """At least 8 matters whose body has a '## Context' section AND that
    section is >= 400 chars. These are the gold Opus-authored records.
    """
    good: list[str] = []
    for path, _, body in _records("matter"):
        m = re.search(r"## Context\s*\n+(.*?)(?=\n##\s|\Z)", body, re.DOTALL)
