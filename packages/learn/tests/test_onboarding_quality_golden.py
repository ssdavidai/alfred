def _parse_md(path: Path) -> tuple[dict[str, Any], str]:
    """Split a vault .md into (frontmatter_dict, body_str)."""
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n(.*)", text, re.DOTALL)
    if not m:
        return {}, text
    try:
        fm = yaml.safe_load(m.group(1)) or {}
    except yaml.YAMLError:
        fm = {}
    return (fm if isinstance(fm, dict) else {}), m.group(2)


def _records(record_type: str) -> list[tuple[Path, dict[str, Any], str]]:
    """Yield (path, frontmatter, body) for every record of one type."""
    out: list[tuple[Path, dict[str, Any], str]] = []
    d = VAULT / record_type
    if not d.exists():
        return out
    for p in sorted(d.glob("*.md")):
        if p.name == ".gitkeep":
            continue
        fm, body = _parse_md(p)
        out.append((p, fm, body))
    return out


def _name(fm: dict[str, Any], path: Path) -> str:
    return str(fm.get("name") or path.stem)


def _tokens(name: str) -> set[str]:
    return {t.lower() for t in re.findall(r"[A-Za-zÀ-ÿ0-9]+", name) if t}


def _token_overlap(a: str, b: str) -> float:
    ta, tb = _tokens(a), _tokens(b)
    if not ta or not tb:
        return 0.0
    inter = ta & tb
    return len(inter) / min(len(ta), len(tb))


# Service-summary-note regex (per GENERATORS.md §16).
_SERVICE_NOTE_RE = re.compile(
    r"^[A-Za-z0-9.\- ]+? (Service Emails( Summary)?|Email Digest"
    r"|Activity Summary|Notifications? Summary|Service & Notification Summary"
    r"|Service Relationship Overview|Emails and Updates"
    r"|Security Alerts|Billing Issue Notifications)\b",
    re.IGNORECASE,
)

# Domain-shape regex for org-name detection.
_DOMAIN_LIKE_RE = re.compile(r"\.(com|io|net|org|ai|co|so|hu|uk|de|us|app|dev)$", re.IGNORECASE)


