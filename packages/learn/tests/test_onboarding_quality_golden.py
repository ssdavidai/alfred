def test_no_domain_stub_matters() -> None:
    """A matter whose name ends ' Project', has a `domain:` frontmatter key,
    AND has a body shorter than 300 chars is a `generate_matter_pack` fallback
    stub (packs.py:338) — KILL per GENERATORS.md §6.
    """
    offenders: list[str] = []
    for path, fm, body in _records("matter"):
        name = _name(fm, path)
        if (
            name.endswith(" Project")
            and "domain" in fm
            and len(body.strip()) < 300
        ):
            offenders.append(path.name)
    if offenders:
        pytest.fail(
            f"{len(offenders)} domain-stub matter records "
            f"(generate_matter_pack fallback junk): {offenders}"
        )


def test_no_inner_circle_autogenerated_matters() -> None:
    """A matter with `tier: inner_circle` AND an `Auto-generated` body is the
    same fallback's signature. The Opus matter generator never writes either
    marker.
    """
    offenders: list[str] = []
    for path, fm, body in _records("matter"):
        if str(fm.get("tier") or "").lower() == "inner_circle" and "Auto-generated" in body:
            offenders.append(path.name)
    if offenders:
        pytest.fail(
            f"{len(offenders)} inner_circle + 'Auto-generated' matters "
            f"(packs.py:338 fallback): {offenders}"
        )


def test_no_per_service_sender_notes() -> None:
    """No note whose name is a service-email-cluster summary.

    These come from the external alfred-vault curator over batch_processor's
    inbox drops (GENERATORS.md §16). Belongs in alfred-state.db.observation,
    not vault.
    """
    offenders: list[str] = []
    for path, fm, _ in _records("note"):
        name = _name(fm, path)
        if _SERVICE_NOTE_RE.match(name):
            offenders.append(name)
    if offenders:
        pytest.fail(
            f"{len(offenders)} service-summary notes (curator junk): "
            f"{offenders}"
        )


def test_no_near_duplicate_notes() -> None:
    """No two notes whose name-token overlap is >= 0.6 (e.g. the 4 GitHub
    summaries that all describe the same sender domain).
    """
    notes = [(_name(fm, p), p.name) for p, fm, _ in _records("note")]
    pairs: list[tuple[str, str, float]] = []
    for i, (na, fa) in enumerate(notes):
        for nb, fb in notes[i + 1:]:
            ov = _token_overlap(na, nb)
            if ov >= 0.6:
                pairs.append((fa, fb, round(ov, 2)))
    if pairs:
        pytest.fail(
            f"{len(pairs)} near-duplicate note pairs (overlap >= 0.6): "
            f"{pairs}"
        )


def test_no_non_human_persons() -> None:
    """No person whose name flags as non-human:
      - ends with 'Notification' / 'Notifications'
      - contains '@'
      - contains a domain-like substring ('.com', '.io', ...)
      - has only 1 capitalized token (likely truncation: 'David Szabo-St')
    """
    offenders: list[tuple[str, str]] = []
    for path, fm, _ in _records("person"):
        name = _name(fm, path)
        why: list[str] = []
        if re.search(r"\bnotifications?$", name, re.IGNORECASE):
            why.append("notifications-suffix")
        if "@" in name:
            why.append("contains-@")
        if _DOMAIN_LIKE_RE.search(name):
            why.append("domain-substring")
        caps = [t for t in name.split() if t[:1].isupper()]
        if len(caps) < 2:
            why.append("only-one-cap-token")
        if why:
            offenders.append((name, ",".join(why)))
    if offenders:
        pytest.fail(
            f"{len(offenders)} non-human / malformed person records: "
            f"{offenders}"
        )


def test_no_owner_duplicates() -> None:
    """No two person records with token-overlap >= 0.65 (one is a truncation
    or alias of the other), unless one declares the other in `aliases:`.

    Threshold 0.65 (not 0.7) because the live case 'David Szabo-St' vs
    'David Szabo-Stuban' tokenises to {david, szabo, st} vs
    {david, szabo, stuban} — overlap 0.667 (the hyphen splits the surname).
    """
    persons = [(_name(fm, p), fm, p.name) for p, fm, _ in _records("person")]
    offenders: list[tuple[str, str, float]] = []
    for i, (na, fma, fa) in enumerate(persons):
        for nb, fmb, fb in persons[i + 1:]:
            ov = _token_overlap(na, nb)
            if ov < 0.65:
                continue
            # explicit alias declared?
            aliases_a = [str(x).lower() for x in (fma.get("aliases") or [])]
            aliases_b = [str(x).lower() for x in (fmb.get("aliases") or [])]
            if nb.lower() in aliases_a or na.lower() in aliases_b:
                continue
            offenders.append((fa, fb, round(ov, 2)))
    if offenders:
        pytest.fail(
            f"{len(offenders)} duplicate-or-truncation person pairs: "
            f"{offenders}"
        )


def test_no_domain_only_orgs() -> None:
    """No org whose name is a bare domain (matches `\\.com$`, `\\.io$`, ...)
    UNLESS the same name token appears in vault/USER.md (legitimate context).
    """
    user_md_text = ""
    user_md = VAULT / "USER.md"
    if user_md.exists():
        user_md_text = user_md.read_text(encoding="utf-8").lower()
    offenders: list[str] = []
    for path, fm, _ in _records("org"):
        name = _name(fm, path)
        if _DOMAIN_LIKE_RE.search(name) and name.lower() not in user_md_text:
            offenders.append(name)
    if offenders:
        pytest.fail(f"{len(offenders)} domain-only orgs: {offenders}")


def test_instinct_confidence_grounded_in_observations() -> None:
    """No instinct with observation_count == 0 AND confidence_score >= 0.5.

    Day-zero instincts must start at the Asking tier; the discretion gate
    earns confidence from observed decisions, not from an LLM-stamped prior.
    See GENERATORS.md §7.
    """
    offenders: list[tuple[str, float, int]] = []
    for path, fm, _ in _records("instinct"):
        # input_patterns may be a JSON-string in the packs_opus path
        obs = fm.get("observation_count")
        conf = fm.get("confidence_score")
        try:
            obs_n = int(obs) if obs is not None else 0
        except (TypeError, ValueError):
            obs_n = 0
        try:
            conf_f = float(conf) if conf is not None else 0.0
        except (TypeError, ValueError):
            conf_f = 0.0
        if obs_n == 0 and conf_f >= 0.5:
            offenders.append((path.name, conf_f, obs_n))
    if offenders:
        pytest.fail(
            f"{len(offenders)} instincts with unearned confidence "
            f"(obs=0, conf>=0.5): {offenders}"
        )


